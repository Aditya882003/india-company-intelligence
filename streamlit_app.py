def pct(x) -> str:
    return "—" if pd.isna(x) else f"{float(x):,.1f}%"


def money_ind(x) -> str:
    if pd.isna(x):
        return "—"
    x = float(x)
    if abs(x) >= 1e12:
        return f"₹{x/1e12:.2f}T"
    if abs(x) >= 1e9:
        return f"₹{x/1e9:.1f}B"
    if abs(x) >= 1e6:
        return f"₹{x/1e6:.1f}M"
    return f"₹{x:,.0f}"


