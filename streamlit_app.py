def connect() -> sqlite3.Connection:
    return sqlite3.connect(DB_PATH)


def q(sql: str, params=()) -> pd.DataFrame:
    with connect() as conn:
        return pd.read_sql_query(sql, conn, params=params)


@st.cache_data(ttl=300)
def load_all():
    companies = q("SELECT * FROM company_master")
    prices = q("SELECT * FROM price_daily ORDER BY trade_date")
    financials = q("SELECT * FROM financial_snapshot ORDER BY as_of_date DESC")
    news = q("SELECT * FROM news_articles ORDER BY published_at DESC")
    # Backward compatibility with databases generated by v1 of the project.
    if "aliases" not in companies.columns:
        companies["aliases"] = ""
    for col, default in {
        "source": "Unknown", "company_name": "", "summary": "", "sentiment": "Neutral",
        "event_type": "General Market", "coverage_count": 1, "corroboration": "Single source"
    }.items():
        if col not in news.columns:
            news[col] = default
    logs = q("SELECT * FROM etl_run_log ORDER BY run_ts_utc DESC")
    return companies, prices, financials, news, logs


@st.cache_data(ttl=12, show_spinner=False)
def live_quote(ticker: str) -> dict:
    try:
        quote = fetch_yahoo_quote(ticker)
    except Exception as exc:
        quote = {
            "ticker": ticker,
            "source": "Yahoo Finance / yfinance",
            "status": f"ERROR: {type(exc).__name__}",
            "price": None,
        }

    # If live provider fails, use the latest stored market record.
    if quote.get("price") is None:
        try:
            hist = q(
                "SELECT * FROM price_daily WHERE ticker=? ORDER BY trade_date DESC LIMIT 2",
                (ticker,),
            )
            if not hist.empty:
                latest = hist.iloc[0]
                price = float(latest["close"])
                prev = (
                    float(hist.iloc[1]["close"])
                    if len(hist) > 1 and pd.notna(hist.iloc[1]["close"])
                    else None
                )
                change = price - prev if prev else None
                pct_change = (change / prev * 100) if prev else None

                return {
                    "ticker": ticker,
                    "source": "Scheduled ETL (cached close)",
                    "status": "CACHED",
                    "price": price,
                    "previous_close": prev,
                    "change": change,
                    "pct_change": pct_change,
                    "day_high": None,
                    "day_low": None,
                    "volume": (
                        float(latest["volume"])
                        if "volume" in latest.index and pd.notna(latest["volume"])
                        else None
                    ),
                    "timestamp_utc": f"{latest['trade_date']}T00:00:00+00:00",
                }
        except Exception:
            pass

    return quote


