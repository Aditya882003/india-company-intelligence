def render_chatbot(companies, scored, prices, financials, news):
    st.subheader("🤖 Analyst Copilot")
    st.caption("Ask the dashboard questions in plain English. Answers are grounded in the current company, market, financial and multi-source news data; no paid AI API key is required.")
    st.markdown("**Try:** " + " · ".join(SUGGESTED_PROMPTS))
    if "chat_history" not in st.session_state:
        st.session_state.chat_history = []
    for role, message in st.session_state.chat_history:
        with st.chat_message(role):
            st.markdown(message)
    prompt = st.chat_input("Ask: What is HDFC Bank's live price? Why is Reliance high attention?")
    if prompt:
        st.session_state.chat_history.append(("user", prompt))
        with st.chat_message("user"):
            st.markdown(prompt)
        with st.chat_message("assistant"):
            with st.spinner("Checking current dashboard data…"):
                response = answer_query(prompt, companies, scored, prices, financials, news, live_quote_fn=live_quote)
            st.markdown(response)
        st.session_state.chat_history.append(("assistant", response))
    if st.button("Clear chat", key="clear_chat"):
        st.session_state.chat_history = []
        st.rerun()


def analysis_narrative(c, news_count: int, corr: int) -> list[str]:
    points = []
    if pd.notna(c.get("return_30d")):
        points.append(f"30-day momentum is {c['return_30d']:.1f}%, with market stress score {int(c.get('market_score',0))}.")
    if pd.notna(c.get("volatility_30d")):
        points.append(f"Annualised 30-day volatility is {c['volatility_30d']:.1f}% and the 90-day drawdown is {c.get('max_drawdown_90d',np.nan):.1f}%.")
    if pd.notna(c.get("revenue_growth_pct")):
        points.append(f"Latest available revenue growth is {c['revenue_growth_pct']:.1f}% and profit growth is {c.get('profit_growth_pct',np.nan):.1f}%.")
    if news_count:
        extra = f"; {corr} corroborated clusters" if corr else ""
        points.append(f"The news layer found {news_count} headlines in the last 7 days{extra}.")
    points.append("Use the source-verification panel before treating any single market or news observation as confirmed.")
    return points


def render_live_pulse(universe: pd.DataFrame, companies: pd.DataFrame):
    st.subheader("⚡ Live Market Pulse")
    st.caption("Live quote layer refreshes while this session is active. Historical analytics remain based on the scheduled ETL dataset.")
    top_names = universe.sort_values("attention_score", ascending=False)["company_name"].head(8).tolist()
    live_company = st.selectbox("Live focus company", top_names, key="live_focus_company")
    ticker = companies.loc[companies["company_name"] == live_company, "ticker"].iloc[0]
    interval = st.select_slider("Refresh live quote every", options=[10, 20, 30, 60], value=20, format_func=lambda x: f"{x}s")
    start = st.checkbox("Auto-refresh live view", value=True)
    run_every = f"{interval}s" if start else None

    @st.fragment(run_every=run_every, key="live_pulse_fragment")
    def _live_fragment():
        quote = live_quote(ticker)
        last = quote.get("price")
        chg = quote.get("pct_change")
        status = quote.get("status", "UNKNOWN")
        ts = pd.to_datetime(quote.get("timestamp_utc"), utc=True, errors="coerce")
        ts_ist = ts.tz_convert(IST) if pd.notna(ts) else pd.Timestamp.now(tz=IST)
        col = "positive" if (chg or 0) > 0 else "negative" if (chg or 0) < 0 else "neutral"
        c1, c2, c3, c4, c5 = st.columns(5)
        c1.metric(live_company, f"₹{last:,.2f}" if last is not None else "—", f"{chg:.2f}%" if chg is not None else None)
        c2.metric("Day high", f"₹{quote['day_high']:,.2f}" if quote.get("day_high") is not None else "—")
        c3.metric("Day low", f"₹{quote['day_low']:,.2f}" if quote.get("day_low") is not None else "—")
        c4.metric("Volume", f"{quote['volume']:,.0f}" if quote.get("volume") is not None else "—")
        c5.metric("Feed", "OK" if status == "OK" else status)
        st.markdown(f'<span class="live-pill">● LIVE QUOTE • {ts_ist.strftime("%d %b %Y %H:%M:%S IST")} • Yahoo Finance / yfinance</span>', unsafe_allow_html=True)
        intr = intraday_chart(ticker)
        if not intr.empty:
            fig = go.Figure()
            fig.add_trace(go.Scatter(x=intr["Datetime"], y=intr["Close"], name="Last traded price", mode="lines"))
            fig.update_layout(height=390, margin=dict(l=10,r=10,t=50,b=10), title="Intraday price", hovermode="x unified")
            st.plotly_chart(fig, use_container_width=True, key=f"live_intraday_{ticker}")
    _live_fragment()


